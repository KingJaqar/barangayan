import { formatCentavosAsPHP, formatDateTime } from '@barangayan/shared';
import type { z } from 'zod';
import type { paidReceiptRow } from '../../data/schemas';
import { paymentMethodName } from './assessment';

/** The fields of a paid receipt, all read from the committed payment and its request. */
export type Receipt = {
  paymentId: string;
  reference: string;
  documentName: string | null;
  amountCentavos: number;
  documentFeeCentavos: number | null;
  paidAt: string;
  method: string;
  transactionRef: string | null;
};

export function toReceipt(row: z.infer<typeof paidReceiptRow>): Receipt {
  return {
    paymentId: row.id,
    reference: row.service_requests.reference_number,
    documentName: row.service_requests.document_types?.name ?? null,
    amountCentavos: row.amount_centavos,
    documentFeeCentavos: row.document_fee_centavos,
    paidAt: row.paid_at ?? row.created_at,
    method: paymentMethodName(row.method),
    transactionRef: row.paymongo_payment_id ?? row.paymongo_source_id ?? row.paymongo_payment_intent_id,
  };
}

/** Ordered label/value lines shared by the receipt screen and the PDF. */
export function receiptLines(receipt: Receipt): [label: string, value: string][] {
  const lines: [string, string][] = [['Reference number', receipt.reference]];
  if (receipt.documentName) lines.push(['Document', receipt.documentName]);
  lines.push(['Date and time', formatDateTime(receipt.paidAt)], ['Payment method', receipt.method]);
  if (receipt.documentFeeCentavos !== null) lines.push(['Document fee', formatCentavosAsPHP(receipt.documentFeeCentavos)]);
  lines.push(['Amount paid', formatCentavosAsPHP(receipt.amountCentavos)]);
  if (receipt.transactionRef) lines.push(['Transaction reference', receipt.transactionRef]);
  return lines;
}

export function escapeHtml(value: string): string {
  return value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;');
}

/**
 * A self-contained HTML receipt for `expo-print`. It embeds no image, so iOS's WKWebView
 * limitation on local file URLs does not apply; any image added later must be inlined as a data URI.
 */
export function receiptHtml(receipt: Receipt, generatedAt: Date): string {
  const rows = receiptLines(receipt).map(([label, value]) => `<tr><th>${escapeHtml(label)}</th><td>${escapeHtml(value)}</td></tr>`).join('');
  return `<!doctype html><html><head><meta charset="utf-8" /><style>
body{font-family:-apple-system,Helvetica,Arial,sans-serif;color:#1a1a1a;margin:32px;font-size:13px}
.brand{font-size:20px;color:#0F6E5B;margin:0 0 2px}.sub{color:#666;margin:0 0 20px}
.status{display:inline-block;margin:12px 0 20px;padding:6px 14px;border-radius:999px;background:#d8ece7;color:#0F6E5B;font-weight:bold}
.amount{font-size:28px;color:#0F6E5B;font-weight:bold;margin:4px 0 24px}
h2{font-size:14px;color:#0F6E5B;border-bottom:1px solid #d8ece7;padding-bottom:4px}
table{border-collapse:collapse;width:100%}th{text-align:left;color:#555;width:190px;vertical-align:top;padding:6px 8px 6px 0}
td{padding:6px 0;vertical-align:top;word-break:break-word}footer{margin-top:32px;color:#888;font-size:10px}
</style></head><body>
<p class="brand">Barangayan</p><p class="sub">Official payment receipt</p>
<span class="status">Payment received</span>
<div class="amount">${escapeHtml(formatCentavosAsPHP(receipt.amountCentavos))}</div>
<h2>Transaction details</h2><table>${rows}</table>
<footer>Generated by the Barangayan resident app on ${escapeHtml(formatDateTime(generatedAt.toISOString()))} from the payment recorded by your barangay.</footer>
</body></html>`;
}

/** A file name that is safe in the cache directory and readable in the share sheet. */
export function receiptFileName(reference: string): string {
  const safe = reference.replace(/[^A-Za-z0-9-]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 60);
  return `Barangayan-receipt-${safe || 'payment'}.pdf`;
}
