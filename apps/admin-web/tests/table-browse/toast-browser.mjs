// Headless regression fixture: real admin UI/host; existing service calls are mocked.
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { build } from 'esbuild';
import postcss from 'postcss';
import tailwind from '@tailwindcss/postcss';
const require = createRequire(import.meta.url);
const root = path.resolve(import.meta.dirname, '../../../..');
const app = path.join(root, 'apps/admin-web');
const appRequire = createRequire(path.join(app, 'package.json'));
process.env.PLAYWRIGHT_BROWSERS_PATH ??= path.join(root, 'dist/admin-table-phase1-browsers');
const { chromium } = require('playwright');
const evidence = path.join(root, 'plans/evidence/admin-toast-coverage');
fs.mkdirSync(evidence, { recursive: true });
const adapters = path.join(import.meta.dirname, 'toast-adapters.js');
const bundle = await build({ entryPoints: [path.join(import.meta.dirname, 'toast-fixture.jsx')], bundle: true, write: false, outdir: 'toast-fixture', jsx: 'automatic', tsconfig: path.join(app, 'tsconfig.json'),
  alias: { react: path.dirname(appRequire.resolve('react/package.json')), 'react-dom': path.dirname(appRequire.resolve('react-dom/package.json')) },
  define: { 'process.env.NODE_ENV': '"development"' }, plugins: [{ name: 'toast-fixtures', setup(builder) {
    builder.onResolve({ filter: /^(next\/navigation|@barangayan\/shared|@\/lib\/supabase\/client|@\/lib\/payments)$/ }, () => ({ path: adapters }));
  } }] });
const cssFile = path.join(app, 'src/app/globals.css');
const css = (await postcss([tailwind({ base: app })]).process(fs.readFileSync(cssFile, 'utf8'), { from: cssFile })).css;
const report = { checks: [], pageErrors: [], limitations: ['Isolated component fixture with mocked service outcomes; no live backend writes or payment/refund operations.'] };
const deadline = setTimeout(() => process.exit(1), 90000);
let browser;
try {
  browser = await chromium.launch({ headless: true, channel: process.env.PLAYWRIGHT_CHANNEL ?? 'chrome' });
  const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
  page.setDefaultTimeout(8000);
  page.on('pageerror', e => report.pageErrors.push(e.message));
  // Inject the compiled fixture directly. No local server or external network is needed.
  await page.setContent('<!doctype html><html lang="en"><head><meta name="viewport" content="width=device-width,initial-scale=1"></head><body><div id="root"></div></body></html>');
  await page.addStyleTag({ content: css + '\n' + bundle.outputFiles.find(f => f.path.endsWith('.css')).text });
  await page.addScriptTag({ content: bundle.outputFiles.find(f => f.path.endsWith('.js')).text });
  const toast = page.locator('[data-sonner-toast][data-visible="true"][data-removed="false"]');
  const dismiss = async () => {
    await page.evaluate(() => document.querySelectorAll('[data-sonner-toast][data-removed="false"] [data-close-button]').forEach(button => button.click()));
    await page.waitForTimeout(400);
  };
  await page.getByRole('button', { name: 'Start processing', exact: true }).evaluate(node => { node.click(); node.click(); });
  await toast.filter({ hasText: 'Request moved to processing.' }).waitFor();
  assert.equal(await toast.count(), 1);
  assert.equal(await page.evaluate(() => window.toastFixture.writes), 1);
  report.checks.push('Rapid repeated fulfillment activation produces one write and one success toast.');
  await dismiss();
  await page.evaluate(() => { window.toastFixture.result = 'error'; });
  await page.getByRole('button', { name: 'Start processing', exact: true }).click();
  await toast.filter({ hasText: 'Could not update the request.' }).waitFor();
  assert.equal(await toast.getAttribute('data-type'), 'error');
  assert.equal(await page.getByText('Fixture rejected change.', { exact: true }).count(), 1);
  report.checks.push('Returned rejection produces one error toast and retains inline recovery.');
  await dismiss();
  await page.evaluate(() => { window.toastFixture.result = 'throw'; });
  await page.getByRole('button', { name: 'Start processing', exact: true }).click();
  await toast.filter({ hasText: "We couldn't confirm the request change." }).waitFor();
  assert.equal(await toast.getAttribute('data-type'), 'warning');
  report.checks.push('Thrown write failure produces an uncertainty warning and releases the action guard.');
  await dismiss();
  await page.getByRole('button', { name: 'Show success', exact: true }).click();
  await toast.filter({ hasText: 'Saved successfully.' }).waitFor();
  assert.equal(await toast.count(), 1);
  await page.waitForTimeout(350);
  const position = await toast.boundingBox();
  report.position = position;
  await page.screenshot({ path: path.join(evidence, 'light-toast.png') });
  assert.ok(position.y >= 70 && Math.abs(position.x + position.width / 2 - 640) < 3);
  const light = await toast.evaluate(node => ({ radius: getComputedStyle(node).borderRadius, bg: getComputedStyle(node).backgroundColor }));
  assert.equal(light.radius, '12px');
  await page.screenshot({ path: path.join(evidence, 'light-toast.png') });
  report.checks.push('Resident-style top-center card sits below the header; duplicate attempt is suppressed.');
  await dismiss();
  await page.getByRole('button', { name: 'Open dialog', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Toast dialog' });
  await dialog.getByRole('button', { name: 'Show success', exact: true }).click();
  await toast.waitFor();
  assert.equal(await page.locator('dialog[open] [data-sonner-toaster]').count(), 1);
  await page.waitForTimeout(350);
  await page.screenshot({ path: path.join(evidence, 'toast-over-native-dialog.png') });
  await page.locator('[data-close-button]').focus();
  await page.waitForTimeout(4300);
  assert.equal(await toast.count(), 1);
  await page.locator('[data-close-button]').click();
  assert.equal(await dialog.count(), 1);
  report.checks.push('One stable host enters the native modal top layer; keyboard focus pauses dismissal and closing the toast preserves the dialog.');
  await dialog.getByRole('button', { name: 'Show success', exact: true }).click();
  await toast.waitFor();
  await dialog.getByRole('button', { name: 'Close dialog', exact: true }).click();
  assert.equal(await toast.count(), 1);
  assert.equal(await page.locator('[data-sonner-toaster]').count(), 1);
  report.checks.push('Closing a native modal preserves the existing toast without a duplicate host.');
  await dismiss();
  await page.getByRole('button', { name: 'Toggle theme', exact: true }).click();
  await page.getByRole('button', { name: 'Show error', exact: true }).click();
  await toast.waitFor();
  await page.waitForTimeout(350);
  assert.notEqual(await toast.evaluate(node => getComputedStyle(node).backgroundColor), light.bg);
  await page.screenshot({ path: path.join(evidence, 'dark-toast.png') });
  report.checks.push('Dark theme changes the toast surface and retains the shared layout.');
  await dismiss();
  await page.setViewportSize({ width: 360, height: 780 });
  await page.getByRole('button', { name: 'Long message', exact: true }).click();
  await toast.waitFor();
  await page.waitForTimeout(350);
  const narrow = await toast.boundingBox();
  assert.ok(narrow.x >= 0 && narrow.x + narrow.width <= 361);
  await page.screenshot({ path: path.join(evidence, 'narrow-wrapped-toast.png') });
  await page.getByRole('button', { name: 'Switch account', exact: true }).click();
  await page.waitForTimeout(300);
  assert.equal(await toast.count(), 0);
  report.checks.push('Long text wraps on a narrow viewport; account change clears prior-account notifications.');
  await page.evaluate(() => window.unmountToastFixture());
  assert.equal(await page.locator('[data-admin-toast-layer]').count(), 0);
  assert.deepEqual(report.pageErrors, []);
  report.checks.push('Unmount cleans up the portal; no uncaught browser errors.');
  report.status = 'passed';
} catch (error) { report.status = 'failed'; report.failure = String(error.stack ?? error); throw error; }
finally { fs.writeFileSync(path.join(evidence, 'browser-results.json'), JSON.stringify(report, null, 2) + '\n'); clearTimeout(deadline); await browser?.close(); }
console.log(JSON.stringify(report, null, 2));
